//! `hearth config`: every setting in effect, where its value came from, and
//! what it means. hearth keeps no number in its code; this is where all of
//! them can be seen.

use std::fmt::Write as _;

#[derive(clap::Args)]
pub struct Args {
    /// Only settings whose key contains this, e.g. `supervise` or `deadline`.
    filter: Option<String>,
    /// The built-in settings as a Markdown reference (docs/configuration.md
    /// is this output), ignoring any user file.
    #[arg(long)]
    markdown: bool,
}

/// The reference page: every built-in setting, its default and meaning,
/// grouped by section.
fn markdown(settings: &[hearth_core::config::Setting]) -> String {
    let mut out = String::from(
        "# Configuration\n\nGenerated by `hearth config --markdown`; do not edit by hand. Every value hearth uses lives here, in `crates/hearth-core/config/hearth.toml`; put the keys you want to change in your own file (`$HEARTH_CONFIG`, or `~/.config/hearth/hearth.toml`). `hearth config` shows what is in effect and where each value came from.\n",
    );
    let mut section = "";
    for s in settings {
        let this = s.key.split('.').next().unwrap_or_default();
        if this != section {
            section = this;
            let _ = write!(
                out,
                "\n## `[{section}]`\n\n| Key | Default | Meaning |\n|---|---|---|\n"
            );
        }
        let value = s
            .value
            .as_ref()
            .map_or_else(|| "unset".to_string(), |v| format!("`{v}`"));
        let _ = writeln!(
            out,
            "| `{}` | {} | {} |",
            s.key,
            value.replace('|', "\\|"),
            s.doc.replace('|', "\\|")
        );
    }
    out
}

pub fn run(args: &Args, json: bool) -> Result<String, String> {
    if args.markdown {
        return hearth_core::config::explain_builtin()
            .map(|s| markdown(&s))
            .map_err(|e| e.to_string());
    }
    let settings: Vec<_> = hearth_core::config::explain()
        .map_err(|e| e.to_string())?
        .into_iter()
        .filter(|s| {
            args.filter
                .as_ref()
                .is_none_or(|f| s.key.contains(f.as_str()))
        })
        .collect();
    if json {
        return crate::to_json(&serde_json::json!({
            "user_file": hearth_core::config::user_path(),
            "settings": settings,
        }));
    }
    let mut out = String::new();
    match hearth_core::config::user_path() {
        Some(path) if path.exists() => {
            let _ = writeln!(
                out,
                "user file: {} (merged over the built-in values)\n",
                path.display()
            );
        }
        Some(path) => {
            let _ = writeln!(
                out,
                "no user file at {}: every value is built in\n",
                path.display()
            );
        }
        None => {}
    }
    for s in &settings {
        let value = s
            .value
            .as_ref()
            .map_or_else(|| "(unset)".to_string(), ToString::to_string);
        let _ = writeln!(out, "{} = {value}    [{}]", s.key, s.source);
        if !s.doc.is_empty() {
            let _ = writeln!(out, "    {}", s.doc);
        }
    }
    Ok(out)
}
